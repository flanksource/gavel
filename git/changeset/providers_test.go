package changeset_test

import (
	"context"
	"fmt"
	"path/filepath"
	"strings"

	"github.com/flanksource/gavel/git/changeset"
	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
)

func environment(values map[string]string, payload string) changeset.Environment {
	return changeset.Environment{
		Lookup:   func(key string) string { return values[key] },
		ReadFile: func(string) ([]byte, error) { return []byte(payload), nil },
	}
}

var _ = Describe("CI changesets", func() {
	DescribeTable("normalizes pull request providers and excludes incidental dirty files", func(provider string, merged bool) {
		dir := repository()
		base := strings.TrimSpace(git(dir, "rev-parse", "HEAD"))
		git(dir, "update-ref", "refs/remotes/origin/main", base)
		git(dir, "checkout", "-qb", "feature")
		write(dir, "feature.txt", "feature\n")
		git(dir, "add", "feature.txt")
		git(dir, "commit", "-qm", "feature")
		head := strings.TrimSpace(git(dir, "rev-parse", "HEAD"))
		if merged {
			git(dir, "checkout", "-q", "main")
			git(dir, "merge", "--no-ff", "-qm", "merge", "feature")
		}
		write(dir, "incidental.txt", "generated by the runner\n")
		values := map[string]string{}
		payload := ""
		switch provider {
		case "github":
			values = map[string]string{"GITHUB_ACTIONS": "true", "GITHUB_EVENT_NAME": "pull_request", "GITHUB_EVENT_PATH": "event.json"}
			payload = fmt.Sprintf(`{"pull_request":{"base":{"sha":%q},"head":{"sha":%q}}}`, base, head)
		case "azure":
			values = map[string]string{"TF_BUILD": "True", "BUILD_REASON": "PullRequest", "SYSTEM_PULLREQUEST_TARGETBRANCH": "refs/heads/main", "SYSTEM_PULLREQUEST_SOURCECOMMITID": head}
		case "gitlab":
			values = map[string]string{"GITLAB_CI": "true", "CI_MERGE_REQUEST_IID": "1", "CI_MERGE_REQUEST_DIFF_BASE_SHA": base, "CI_COMMIT_SHA": head}
			if merged {
				values["CI_MERGE_REQUEST_EVENT_TYPE"] = "merged_result"
				values["CI_MERGE_REQUEST_TARGET_BRANCH_SHA"], values["CI_MERGE_REQUEST_SOURCE_BRANCH_SHA"] = base, head
			}
		}
		selected, err := changeset.Resolve(context.Background(), changeset.Options{Dir: dir, Changed: true, Environment: environment(values, payload)})
		Expect(err).NotTo(HaveOccurred())
		Expect(selected.Provider).To(Equal(provider))
		Expect(selected.Paths(dir)).To(Equal([]string{"feature.txt"}))
	}, Entry("GitHub source", "github", false), Entry("GitHub merge", "github", true),
		Entry("Azure source", "azure", false), Entry("Azure merge", "azure", true),
		Entry("GitLab source", "gitlab", false), Entry("GitLab merge", "gitlab", true))

	It("uses a complete pushed range rather than only the latest commit", func() {
		dir := repository()
		base := strings.TrimSpace(git(dir, "rev-parse", "HEAD"))
		for _, file := range []string{"first.txt", "second.txt"} {
			write(dir, file, file)
			git(dir, "add", file)
			git(dir, "commit", "-qm", file)
		}
		head := strings.TrimSpace(git(dir, "rev-parse", "HEAD"))
		selected, err := changeset.Resolve(context.Background(), changeset.Options{Dir: dir, Changed: true, Environment: environment(map[string]string{"GITHUB_ACTIONS": "true", "GITHUB_EVENT_PATH": "event.json", "GITHUB_EVENT_NAME": "push"}, fmt.Sprintf(`{"before":%q,"after":%q}`, base, head))})
		Expect(err).NotTo(HaveOccurred())
		Expect(selected.Paths(dir)).To(Equal([]string{"first.txt", "second.txt"}))
	})
	It("resolves merge groups and GitLab push ranges without adding local files", func() {
		dir := repository()
		base := strings.TrimSpace(git(dir, "rev-parse", "HEAD"))
		write(dir, "queue.txt", "queued changes\n")
		git(dir, "add", "queue.txt")
		git(dir, "commit", "-qm", "queue")
		head := strings.TrimSpace(git(dir, "rev-parse", "HEAD"))
		write(dir, "generated.txt", "incidental\n")
		inputs := []changeset.Environment{
			environment(map[string]string{"GITHUB_ACTIONS": "true", "GITHUB_EVENT_PATH": "event.json", "GITHUB_EVENT_NAME": "merge_group"}, fmt.Sprintf(`{"merge_group":{"base_sha":%q,"head_sha":%q}}`, base, head)),
			environment(map[string]string{"GITLAB_CI": "true", "CI_COMMIT_BEFORE_SHA": base, "CI_COMMIT_SHA": head}, ""),
		}
		for _, env := range inputs {
			selected, err := changeset.Resolve(context.Background(), changeset.Options{Dir: dir, Changed: true, Environment: env})
			Expect(err).NotTo(HaveOccurred())
			Expect(selected.Paths(dir)).To(Equal([]string{"queue.txt"}))
		}
	})
	It("compares the supplied push endpoints even after a force push", func() {
		dir := repository()
		base := strings.TrimSpace(git(dir, "rev-parse", "HEAD"))
		write(dir, "old.txt", "old branch\n")
		git(dir, "add", "old.txt")
		git(dir, "commit", "-qm", "old")
		previous := strings.TrimSpace(git(dir, "rev-parse", "HEAD"))
		git(dir, "checkout", "-qb", "rewritten", base)
		write(dir, "new.txt", "new branch\n")
		git(dir, "add", "new.txt")
		git(dir, "commit", "-qm", "new")
		selected, err := changeset.Resolve(context.Background(), changeset.Options{Dir: dir, Comparison: &changeset.Comparison{Kind: "range", Base: previous, Head: "HEAD"}})
		Expect(err).NotTo(HaveOccurred())
		Expect(selected.Paths(dir)).To(Equal([]string{"new.txt", "old.txt"}))
	})
	It("uses the first parent when a CI job has no previous SHA and handles real root commits", func() {
		dir := repository()
		selected, err := changeset.Resolve(context.Background(), changeset.Options{Dir: dir, Changed: true, Environment: environment(map[string]string{"TF_BUILD": "true", "BUILD_SOURCEVERSION": "HEAD"}, "")})
		Expect(err).NotTo(HaveOccurred())
		Expect(selected.Paths(dir)).To(Equal([]string{"tracked.txt"}))
		write(dir, "second.txt", "second\n")
		git(dir, "add", "second.txt")
		git(dir, "commit", "-qm", "second")
		selected, err = changeset.Resolve(context.Background(), changeset.Options{Dir: dir, Changed: true, Environment: environment(map[string]string{"GITLAB_CI": "true", "CI_COMMIT_SHA": "HEAD", "CI_COMMIT_BEFORE_SHA": strings.Repeat("0", 40)}, "")})
		Expect(err).NotTo(HaveOccurred())
		Expect(selected.Paths(dir)).To(Equal([]string{"second.txt"}))
	})
	It("does not mistake a shallow boundary for a root commit", func() {
		dir := repository()
		write(dir, "second.txt", "second\n")
		git(dir, "add", "second.txt")
		git(dir, "commit", "-qm", "second")
		clone := filepath.Join(GinkgoT().TempDir(), "clone")
		git(dir, "clone", "-q", "--depth=1", "file://"+dir, clone)
		_, err := changeset.Resolve(context.Background(), changeset.Options{Dir: clone, Changed: true, Environment: environment(map[string]string{"TF_BUILD": "true", "BUILD_SOURCEVERSION": "HEAD"}, "")})
		Expect(err).To(MatchError(ContainSubstring("history")))
	})
	DescribeTable("rejects invalid CI state rather than guessing a comparison", func(values map[string]string, payload, expected string) {
		_, err := changeset.Resolve(context.Background(), changeset.Options{Dir: repository(), Changed: true, Environment: environment(values, payload)})
		Expect(err).To(MatchError(ContainSubstring(expected)))
	}, Entry("unknown runner", map[string]string{"CI": "true"}, "", "unknown CI provider"),
		Entry("invalid marker", map[string]string{"CI": "not-a-boolean"}, "", "invalid CI marker"),
		Entry("conflicting runners", map[string]string{"GITHUB_ACTIONS": "true", "TF_BUILD": "true"}, "", "conflicting CI providers"),
		Entry("missing PR data", map[string]string{"GITHUB_ACTIONS": "true", "GITHUB_EVENT_NAME": "pull_request", "GITHUB_EVENT_PATH": "event.json"}, `{}`, "requires pull_request"),
		Entry("invalid event", map[string]string{"GITHUB_ACTIONS": "true", "GITHUB_EVENT_PATH": "event.json"}, `{`, "decode event"))
	It("explicit selectors bypass automatic CI metadata", func() {
		dir := repository()
		write(dir, "untracked.txt", "local\n")
		selected, err := changeset.Resolve(context.Background(), changeset.Options{Dir: dir, Changed: true, Since: "HEAD", Environment: environment(map[string]string{"CI": "true"}, "")})
		Expect(err).NotTo(HaveOccurred())
		Expect(selected.Paths(dir)).To(Equal([]string{"untracked.txt"}))
	})
	It("rejects a target-only checkout for a pull request", func() {
		dir := repository()
		base := strings.TrimSpace(git(dir, "rev-parse", "HEAD"))
		write(dir, "feature.txt", "feature\n")
		git(dir, "add", "feature.txt")
		git(dir, "commit", "-qm", "feature")
		head := strings.TrimSpace(git(dir, "rev-parse", "HEAD"))
		git(dir, "checkout", "-q", base)
		_, err := changeset.Resolve(context.Background(), changeset.Options{Dir: dir, Comparison: &changeset.Comparison{Kind: "pull-request", Base: base, Head: head}})
		Expect(err).To(MatchError(ContainSubstring("neither source")))
	})
})
