package linters

import (
	"context"

	"github.com/flanksource/clicky"
	commonsContext "github.com/flanksource/commons/context"
	"github.com/flanksource/gavel/models"
	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
)

// entityResultLinter reports findings on virtual entity keys and names each
// with its content in Sources, as an in-process linter over database rows does.
type entityResultLinter struct {
	dryRunLinter
	sources map[string]SourceFile
}

func (l entityResultLinter) Name() string { return "entities" }

func (l entityResultLinter) RunResult(commonsContext.Context, *clicky.Task) (*LinterResult, error) {
	var found []models.Violation
	for key := range l.sources {
		found = append(found, models.Violation{File: key, Line: 1, Severity: models.SeverityError})
	}
	return &LinterResult{Violations: found, Sources: l.sources, RawOutput: "linted 2 entities", FileCount: 2}, nil
}

var _ = Describe("ResultLinter", func() {
	const (
		handWritten = "transaction/Fee"
		generated   = "transaction/Generated"
	)
	sources := map[string]SourceFile{
		handWritten: {URL: "https://rules.example/Fee", Content: "<Transaction/>\n"},
		generated:   {URL: "https://rules.example/Generated", Content: "<!-- Code generated by acme; DO NOT EDIT. -->\n<Transaction/>\n"},
	}

	It("keeps the result's Sources and extra fields while gavel sets name, verdict and timing", func() {
		result := RunLinterWithTask(context.Background(), nil, entityResultLinter{sources: sources}, RunOptions{WorkDir: GinkgoT().TempDir()})

		Expect(result.Sources).To(Equal(sources))
		Expect([]any{result.Linter, result.Success, result.Error, result.RawOutput, result.FileCount}).
			To(Equal([]any{"entities", true, "", "linted 2 entities", 2}))
		Expect(result.Violations).To(HaveLen(2))
		Expect(result.Duration).To(BeNumerically(">", 0))
	})

	It("filters a generated source by its Sources content without reading the missing file", func() {
		result := RunLinterWithTask(context.Background(), nil, entityResultLinter{sources: sources}, RunOptions{WorkDir: GinkgoT().TempDir(), Generated: new(false)})

		Expect(result.Error).To(BeEmpty())
		Expect(result.Violations).To(HaveExactElements(HaveField("File", handWritten)))
	})
})
