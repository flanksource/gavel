package linters

import (
	"context"
	"errors"
	"os"
	"path/filepath"

	"github.com/flanksource/clicky"
	commonsContext "github.com/flanksource/commons/context"
	"github.com/flanksource/gavel/models"
	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
)

var _ = Describe("Generated source findings", func() {
	DescribeTable("filters only generated source files", func(name, source string, generated bool) {
		root := GinkgoT().TempDir()
		Expect(os.WriteFile(filepath.Join(root, name), []byte(source), 0o600)).To(Succeed())
		findings := []models.Violation{{File: name, Severity: models.SeverityError}, {Severity: models.SeverityError}}
		exclude := false
		kept, err := filterGeneratedViolations(RunOptions{WorkDir: root, Generated: &exclude}, findings)
		Expect(err).NotTo(HaveOccurred())
		if generated {
			Expect(kept).To(Equal(findings[1:]))
		} else {
			Expect(kept).To(Equal(findings))
		}
	},
		Entry("Go banner", "source.go", "// Code generated by acme; DO NOT EDIT.\npackage example\n", true),
		Entry("TypeScript marker", "source.ts", "/**\n * @generated\n */\nexport const value = 1\n", true),
		Entry("Python banner", "source.py", "#!/usr/bin/python3\n# Code generated by acme; DO NOT EDIT.\nvalue = 1\n", true),
		Entry("protobuf filename", "source.pb.go", "package example\n", true),
		Entry("generator filename", "source_gen.go", "package example\n", true),
		Entry("generated extension", "source.generated.ts", "export const value = 1\n", true),
		Entry("ordinary source", "source.go", "// Package example provides values.\npackage example\n", false),
		Entry("marker inside source", "source.ts", "export const value = '@generated'\n", false),
		Entry("marker after code", "source.py", "value = 1\n# @generated\n", false),
	)

	It("preserves native defaults and explicit inclusion without reading files", func() {
		findings := []models.Violation{{File: "missing.go"}}
		for _, policy := range []*bool{nil, new(true)} {
			kept, err := filterGeneratedViolations(RunOptions{Generated: policy}, findings)
			Expect(err).NotTo(HaveOccurred())
			Expect(kept).To(Equal(findings))
		}
	})

	It("fails with the source path when a reported source cannot be read", func() {
		_, err := filterGeneratedViolations(RunOptions{WorkDir: GinkgoT().TempDir(), Generated: new(false)}, []models.Violation{{File: "missing.go"}})
		Expect(err).To(MatchError(ContainSubstring("missing.go")))
	})

	It("filters explicit generated files before task verdicts and preserves execution failures", func() {
		root := GinkgoT().TempDir()
		GinkgoT().Setenv("HOME", GinkgoT().TempDir())
		Expect(os.WriteFile(filepath.Join(root, "source.go"), []byte("// Code generated by acme; DO NOT EDIT.\npackage example\n"), 0o600)).To(Succeed())
		options := RunOptions{WorkDir: root, Generated: new(false), Scopes: []string{"source.go"}}
		task := clicky.StartTask[*LinterResult]("generated findings", func(ctx commonsContext.Context, task *clicky.Task) (*LinterResult, error) {
			return RunLinterWithTask(ctx, task, generatedTestLinter{}, options), nil
		})
		result, err := task.GetResult()
		Expect(err).NotTo(HaveOccurred())
		Expect(result.Violations).To(BeEmpty())
		Expect(task.IsOk()).To(BeTrue())
		failed := RunLinterWithTask(context.Background(), nil, generatedTestLinter{failure: errors.New("execution failed")}, options)
		Expect(failed.Violations).To(BeEmpty())
		Expect(failed.Success).To(BeFalse())
		Expect(failed.Error).To(ContainSubstring("execution failed"))
	})
})

type generatedTestLinter struct {
	dryRunLinter
	failure error
}

func (l generatedTestLinter) Run(commonsContext.Context, *clicky.Task) ([]models.Violation, error) {
	return []models.Violation{{File: "source.go", Severity: models.SeverityError}}, l.failure
}
